/* Aplica a tabela ao HTML já montado. */
EL._swapOrdenado = null;
EL.tHTML = function (h) {
  if (EL.LANG !== 'en' || !EL.SWAP_EN || typeof h !== 'string') return h;
  if (!EL._swapOrdenado) {
    // frase mais longa primeiro: evita que um termo curto corrompa uma frase que o contém
    EL._swapOrdenado = EL.SWAP_EN.filter(function (p) { return p[0] !== p[1]; })
      .sort(function (a, b) { return b[0].length - a[0].length; });
  }
  var L = EL._swapOrdenado;
  for (var i = 0; i < L.length; i++) h = h.split(L[i][0]).join(L[i][1]);
  for (var k in EL.EF_EN) h = h.split('>' + k + ' +').join('>' + EL.EF_EN[k] + ' +');
  return h;
};
